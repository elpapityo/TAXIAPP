'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('index.html','utf8');
const a=source.indexOf('function applyUberDisplayedDefault(d){');
const b=source.indexOf('function uberAppAmounts(row,settings={}){',a);
assert.ok(a>=0&&b>a,'default helper exists');
const sandbox={number(v){if(v===null||v===undefined||String(v).trim()==='')return null;const n=Number(v);return Number.isFinite(n)?n:null;}};
vm.createContext(sandbox);
vm.runInContext(source.slice(a,b),sandbox);
const apply=d=>vm.runInContext('applyUberDisplayedDefault(d)',vm.createContext({d,number:sandbox.number}));
const make=(pay='U',meter='5000')=>({kind:'ride',raw:{E:'U',N:pay,K:meter},meta:{uberAppDisplayed:''}});
const uber=make();
assert.equal(apply(uber),true);
assert.equal(uber.meta.uberAppDisplayed,'0','Uber order with Uber payment defaults to zero');
assert.equal(uber.meta.uberAppDisplayedDefaulted,true);
assert.equal(apply(uber),false);
uber.raw.K='6200';
assert.equal(apply(uber),false,'zero remains zero for Uber payment');
uber.raw.N='現';
assert.equal(apply(uber),true,'auto-generated default follows payment choice');
assert.equal(uber.meta.uberAppDisplayed,'6200');
uber.raw.K='6800';
assert.equal(apply(uber),true);
assert.equal(uber.meta.uberAppDisplayed,'6800');
uber.meta.uberAppDisplayed='5100';
uber.meta.uberAppDisplayedManual=true;
uber.raw.K='7000';
uber.raw.N='U';
assert.equal(apply(uber),false,'manual entry must win over subsequent changes');
assert.equal(uber.meta.uberAppDisplayed,'5100');
uber.meta.uberAppDisplayed='';
assert.equal(apply(uber),false,'manual empty value must not be auto-filled');
const other=make('現');
assert.equal(apply(other),true);
assert.equal(other.meta.uberAppDisplayed,'5000','in-cab payment defaults to meter');
const unentered=make('現','');
assert.equal(apply(unentered),false,'no meter must not create misleading zero');
const historic=make('現');historic.meta.uberAppDisplayed='4300';
assert.equal(apply(historic),false,'existing user amount is preserved');
assert.equal(historic.meta.uberAppDisplayed,'4300');
const nonUber=make('現');nonUber.raw.E='G';
assert.equal(apply(nonUber),false);
assert.match(source,/if\(target\.dataset\.meta==='uberAppDisplayed'\)s\.draft\.meta\.uberAppDisplayedManual=true/);
assert.match(source,/\['K','E','N'\]\.includes\(col\)&&applyUberDisplayedDefault\(s\.draft\)/);
console.log('Uber defaults passed: Uber pay=0, cabin pay=meter, recalculation, existing and manual edits protected.');
