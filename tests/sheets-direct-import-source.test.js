'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const script=fs.readFileSync('google-apps-script/FirestoreSheetDirectImport.gs','utf8');
new vm.Script(script,{filename:'FirestoreSheetDirectImport.gs'});
assert.match(script,/function firestoreSheetImportMenuCreate_\(/);
assert.match(script,/function firestoreSheetImportCheckboxEdit_\(/);
assert.match(script,/function firestoreSheetDirectImport_\(/);
assert.match(script,/function setupFirestoreSheetImportButton_\(/);
assert.match(script,/function firestoreSheetOwner_\(/);
assert.match(script,/function firestoreSheetFirebaseToken_\(/);
assert.match(script,/function firestoreSheetCandidates_\(/);
assert.match(script,/owner!==active\|\|owner!==effective/);
assert.match(script,/record\.revision<1/);
assert.match(script,/record\.trashed/);
assert.match(script,/firestorePrintSelectedDutyDraft_\(picked\.id,date,token\)/);
assert.doesNotMatch(script,/function (?:doPost|onOpen|onEdit)\(/,'既存GASの受信・マクロを置換しない');
assert.doesNotMatch(script,/getOAuthToken\(\)[\s\S]{0,100}firestore\.googleapis\.com/,'Google IAM経由の全員原本取得を許さない');
assert.match(script,/eventUser!==undefined/);
assert.match(script,/e\.range\.setValue\(false\)/);
console.log('本人Firestore直接取込GAS：構文、接続、既存受信非置換を確認');
