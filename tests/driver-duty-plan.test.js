'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const a=html.indexOf('function driverDutyPlan(){');
const b=html.indexOf('function currentDutySummary(shift){',a);
assert.ok(a>=0&&b>a);
const model={prefs:{dutyPlan:{type:'隔日勤務',hours:'20',distanceKm:'300'}}};
const ctx={model,number(v){if(v==null||String(v).trim()==='')return null;const n=Number(v);return Number.isFinite(n)?n:null;},safeText:String};
vm.createContext(ctx);vm.runInContext(html.slice(a,b),ctx);
const shift={startedIso:new Date('2026-10-19T00:00:00Z').toISOString(),gpsTrip:{tripKm:120}};
ctx.shift=shift;ctx.now=Date.parse('2026-10-19T12:30:00Z');
const remaining=vm.runInContext('dutyRemaining(shift,now)',ctx);
assert.equal(remaining.minutes,450,'20 hours minus 12.5 hours = 7.5 hours');
assert.equal(remaining.distanceKm,180);
assert.equal(vm.runInContext('driverDutyPlan().type',ctx),'隔日勤務');
const imported={date:'2026-10-19',startedAt:'00:00:00',gpsTrip:{tripKm:120}};
ctx.shift=imported;
// ISO(UTC)とタイムゾーンなしの出庫時刻は別の起点。ローカル出庫から12.5時間後を指定する。
ctx.now=Date.parse(`${imported.date}T${imported.startedAt}`)+12.5*3600000;
assert.equal(vm.runInContext('dutyRemaining(shift,now).minutes',ctx),450,'imported duty with local start clock remains calculable');
model.prefs.dutyPlan={hours:'',distanceKm:''};
const unset=vm.runInContext('dutyRemaining(shift,now)',ctx);
assert.equal(unset.minutes,null,'unset time should not invent a shift limit');
assert.equal(unset.distanceKm,null,'unset distance should not invent a limit');
assert.match(html,/data-duty-plan="hours"/);
assert.match(html,/data-duty-plan="distanceKm"/);
assert.match(html,/data-duty-plan="type"/);
assert.match(html,/getShift\(\)\?\.draft\|\|getShift\(\)\?\.waiting/,'no fixed banner while cruising');
assert.match(html,/if\(e\.type==='change'\)toast\('1乗務の勤務設定を保存しました'\)/);
assert.doesNotMatch(html,/if\(e\.type!=='change'\)return;\s*const key=target\.dataset\.dutyPlan/);
console.log('Per-driver duty plan settings and remaining time/distance passed');
