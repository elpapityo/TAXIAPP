'use strict';
const assert=require('node:assert/strict');
const R=require('../gps-test-rows.js');
let state=R.fresh();
assert.equal(state.rows.length,2);
assert.equal(R.derive(state).rows[0].finalKm,null);
state=R.startKm?state:R.setStartKm(state,0);
state=R.startGps(state,4.2,false,{place:'兵庫県伊丹市',at:10000});
state=R.captureRow(state,0,5.2,{place:'兵庫県伊丹市千僧',at:15000});
let view=R.derive(state);
assert.equal(view.rows[0].finalKm,1);
assert.equal(view.rows[0].deltaKm,1);
assert.equal(view.rows[0].place,'兵庫県伊丹市千僧');
assert.equal(view.rows[0].at,15000);
// User scenario: overwrite first row with 20km; the next GPS increases by 0.750km.
state=R.setManualKm(state,0,20);
view=R.derive(state);assert.equal(view.rows[0].finalKm,20);
state=R.captureRow(state,1,5.95,{place:'兵庫県川西市',at:20000});
view=R.derive(state);
assert.equal(view.rows[1].deltaKm,0.75);
assert.equal(view.rows[1].finalKm,20.75);
assert.equal(view.rows[1].place,'兵庫県川西市');
assert.equal(view.startPlace,'兵庫県伊丹市');
state=R.appendRow(state);
state=R.captureRow(state,2,6.5,{place:'兵庫県宝塚市',at:21000});
assert.equal(R.derive(state).rows[2].finalKm,21.3);
state=R.setManualKm(state,0,30);
assert.equal(R.derive(state).rows[1].finalKm,30.75,'past correction adjusts following rows');
assert.equal(R.derive(state).rows[2].finalKm,31.3);
assert.throws(()=>R.captureRow(state,0,6.8),/後の行/,'must not silently rewrite future readings');
assert.throws(()=>R.captureRow(state,2,2.0),/小さく/);
assert.throws(()=>R.setStartKm(state,-2),/距離/);
assert.throws(()=>R.captureRow(R.fresh(),0,1),/スタート行/);
const blank=R.fresh();
assert.throws(()=>R.captureRow(R.startGps(blank,1),1,3),/先に1行目/);
assert.throws(()=>R.startGps(state,3),/リセット/);
const cleared=R.startGps(state,9,true,{place:'日本',at:22222});
assert.equal(cleared.rows[0].gpsKm,null);
assert.equal(cleared.rows[0].place,'');
assert.equal(cleared.startAt,22222);
console.log('GPS numbered row simulation passed: start, two rows, 1=20 correction → 2=20.750, address/time per row, recalculation and duplicate protection.');
